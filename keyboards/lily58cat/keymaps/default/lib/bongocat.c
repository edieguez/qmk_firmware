static uint32_t bongo_timer       = 0;
static uint8_t  current_tap_frame = 0;
static bool     idle_drawn        = false;

void render_bongocat(void) {
    // The on/off state comes from the master (SPLIT_OLED_ENABLE); skip
    // drawing while off.
    if (!is_oled_on()) {
        return;
    }

    uint8_t wpm = get_current_wpm();
    if (wpm < ANIM_WPM_LOWER) {
        // Static frame, drawn once until typing starts again.
        if (!idle_drawn) {
            oled_write_raw_P(idle, ANIM_SIZE);
            idle_drawn = true;
        }
        return;
    }
    idle_drawn = false;

    uint16_t speedup  = (uint16_t)wpm * ANIM_FRAME_STEP_X2 / 2;
    uint16_t duration = speedup >= ANIM_FRAME_DURATION_MAX - ANIM_FRAME_DURATION_MIN ? ANIM_FRAME_DURATION_MIN : ANIM_FRAME_DURATION_MAX - speedup;
    if (timer_elapsed32(bongo_timer) > duration) {
        bongo_timer       = timer_read32();
        current_tap_frame = !current_tap_frame;
        oled_write_raw_P(tap[current_tap_frame], ANIM_SIZE);
    }
}
